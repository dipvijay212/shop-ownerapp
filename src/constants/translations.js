// Substitutes {name} placeholders. Without this a string like
// '{count} delivered' rendered the braces literally on screen.
//
// The second argument is overloaded for compatibility: existing callers pass a
// fallback string, newer ones pass a params object.
//   t('addProduct', 'Add Product')        → fallback
//   t('deliveredCount', { count: 3 })     → params
//   t('roundAway', 'x away', { count: 3 }) → both
export const getTranslation = (lang = 'en', key = '', fallbackOrParams = '', maybeParams) => {
  const dictionary = translations[lang] || translations.en;
  const secondIsParams = !!fallbackOrParams && typeof fallbackOrParams === 'object';
  const fallback = secondIsParams ? '' : fallbackOrParams;
  const params = secondIsParams ? fallbackOrParams : maybeParams;

  const template = dictionary[key] || translations.en[key] || fallback || key;
  if (!params) return template;
  return String(template).replace(/\{(\w+)\}/g, (match, name) =>
    params[name] === undefined || params[name] === null ? match : String(params[name]),
  );
};

// `t` is memoised on the active language rather than rebuilt every render.
// It goes into useCallback/useMemo/useEffect dependency arrays across the app,
// and a fresh closure each render would invalidate every one of them on every
// render. The returned object is memoised for the same reason.
export const useTranslation = () => {
  const auth = useContext(AuthContext);
  const lang = auth?.appLanguage || 'en';

  const t = useCallback(
    (key, defaultValOrParams, params) => getTranslation(lang, key, defaultValOrParams, params),
    [lang],
  );

  return useMemo(() => ({ t, appLanguage: lang }), [t, lang]);
};
